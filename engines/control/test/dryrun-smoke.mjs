// ---------- 小测试框架 ----------
let passed = 0
const failures = []
function check(name, fn) {
  try {
    fn()
    passed++
    console.log(`PASS  ${name}`)
  } catch (error) {
    failures.push({ name, message: error?.message ?? String(error) })
    console.log(`FAIL  ${name}\n        ${String(error?.message ?? error).split('\n').join('\n        ')}`)
  }
}
async function checkAsync(name, fn) {
  try {
    await fn()
    passed++
    console.log(`PASS  ${name}`)
  } catch (error) {
    failures.push({ name, message: error?.message ?? String(error) })
    console.log(`FAIL  ${name}\n        ${String(error?.message ?? error).split('\n').join('\n        ')}`)
  }
}
function assert(condition, message) {
  if (!condition) throw new Error(message)
}
function assertEqual(actual, expected, what) {
  if (actual !== expected) throw new Error(`${what}：期望 ${JSON.stringify(expected)}，实际 ${JSON.stringify(actual)}`)
}

/** The whole point: a rehearsal must not have touched a single mutating call. */
function expectNoMutation(snap, label) {
  const total = mutationTotal(snap)
  assertEqual(total, 0, `${label} 出现了 ${total} 次会动手的调用（${show(snap)}）`)
}
function expectOnlyDryRunAudit() {
  const kinds = [...new Set(auditLog.map(entry => entry.kind))]
  const bad = kinds.filter(kind => kind !== 'dry-run')
  assertEqual(bad.length, 0, `dryRun 期间写了非 dry-run 的审计条目：${bad.join(',')}`)
  assert(auditLog.every(entry => entry.outcome === 'not-executed'), 'dryRun 审计的 outcome 必须全是 not-executed')
}

