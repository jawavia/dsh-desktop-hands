// real 描述真执行的拒绝方式：抛错（进入注入层前守卫）或返回 ⛔（更早的闸门拦下）。
const PARITY = [
  ['click 缺坐标', { action: 'click' }, 'click 需要 x/y 或 imageX/imageY', { kind: 'throw', message: 'click 需要 x/y 或 imageX/imageY' }],
  ['drag 缺终点', { action: 'drag', x: 1, y: 2 }, 'drag 需要起点 x/y 和终点 toX/toY', { kind: 'throw', message: 'drag 需要起点 x/y 和终点 toX/toY' }],
  ['type 缺 text', { action: 'type' }, 'type 需要 text', { kind: 'throw', message: 'type 需要 text' }],
  ['key 缺 key', { action: 'key' }, 'key 需要 key 名', { kind: 'throw', message: 'key 需要 key 名' }],
  ['hotkey 缺 keys', { action: 'hotkey' }, 'hotkey 需要 keys', { kind: 'throw', message: 'hotkey 需要 keys' }],
  ['open 缺 app', { action: 'open' }, 'open 需要 app', { kind: 'refuse' }],
  ['未知动作', { action: 'teleport' }, '未知动作：teleport', { kind: 'throw', message: '未知动作：teleport' }],
]
for (const [label, step, previewProblem, real] of PARITY) {
  await checkAsync(`参数校验一致：${label}（dryRun 报「${previewProblem}」，真执行同样拒绝）`, async () => {
    reset()
    const preview = String(await act().execute({ ...step, dryRun: true }))
    expectNoMutation(snapshot(), `dryRun(${label})`)
    assert(preview.includes(`参数：${previewProblem}`), `dryRun 没报出参数问题：${preview}`)
    if (real.kind === 'refuse') {
      // open 会在更早的安全闸被拦下（敏感动作要 confirmed），同样是"什么都没做"
      const out = String(await act().execute({ ...step, observe: false }))
      assert(out.startsWith('⛔'), `真执行应当被拦下：${out.slice(0, 120)}`)
      expectNoMutation(snapshot(), `real(${label})`)
      return
    }
    let thrown = null
    try {
      await act().execute({ ...step, observe: false })
    } catch (error) {
      thrown = error
    }
    assert(thrown, `真执行应当抛错（${real.message}）`)
    assertEqual(thrown.message, real.message, '真执行的错误信息')
  })
}

