#!/usr/bin/env node
// engines/control/test/dryrun-smoke.mjs —— 证明 screen_act / screen_sequence 的 dryRun 是真预演：
// 零注入、零移动、零截图、零授权、不伪装成执行。
//
// 做法：把 src/ 原样复制到临时沙箱，只把 tools.js 依赖的"会动手的模块"
// （win32 / capture / uia / clipboard / overlay）与"会记授权/审计的模块"
// （policy / gate / deny）替换成计数桩模块，再 import 沙箱里那份**原文未改**的 tools.js。
// 同一套桩下：
//   ① dryRun 调用 → 所有注入/移动/截图/前台切换计数必须为 0，审计只允许出现 dry-run 条目；
//   ② 同样的调用去掉 dryRun → 计数必须 > 0（证明桩是活的、测试不是空转）；
//   ③ 参数合法性：dryRun 报的「参数」问题与真执行抛的错一致；
//   ④ 静态兜底：注入层 performAction / uiaStep 里必须有拒绝 dryRun 的守卫。
//
// 为什么不再用 `node:test` 的 `mock.module`（2026-11-08 修）：
//   `mock.module` 是**实验性** API（Node 22 需要 --experimental-test-module-mocks 且在 22.x 上
//   对 ESM 依赖不生效 → policy.js 桩没挂上、报 "WRITE_ACTIONS 不是导出"，带标志单跑也红）。
//   计数桩本可以直接落到沙箱文件里，不需要任何实验性接口：不再依赖 Node 版本/实验性标志，
//   也不会"自动补 flag 重跑"掩盖环境问题（本次实测 Node v24.20.0，与 engines.node 一致）。
//
// 用法：node test/dryrun-smoke.mjs   （不需要任何额外参数）
